def make_dict_id(prefix: str, word: str) -> str:
    h = hashlib.md5(word.encode("utf-8")).hexdigest()[:10]
    return f"{prefix}_{h}"


def split_plain_segment(text: str, kana_words_sorted: list[str], kana_id_map: dict[str, str]) -> list[dict]:
    if not text:
        return []
    pattern = re.compile("|".join(re.escape(w) for w in kana_words_sorted))
    out = []
    pos = 0
    for m in pattern.finditer(text):
        if m.start() > pos:
            out.append({"text": text[pos:m.start()], "reading": None})
        w = m.group(0)
        out.append({"text": w, "reading": None, "dict_id": kana_id_map[w]})
        pos = m.end()
    if pos < len(text):
        out.append({"text": text[pos:], "reading": None})
    return out


def annotate_question_text(
    text: str,
    word_to_entry: dict[str, dict],
    kana_words_sorted: list[str],
    kana_id_map: dict[str, str],
) -> list[dict]:
    kanji_re = re.compile(r"[\u4E00-\u9FAF\u3400-\u4DBF々]+")
    segments = []
    pos = 0
    for m in kanji_re.finditer(text):
        if m.start() > pos:
            plain = text[pos:m.start()]
            segments.extend(split_plain_segment(plain, kana_words_sorted, kana_id_map))
        kword = m.group(0)
        if kword in word_to_entry:
            entry = word_to_entry[kword]
            segments.append({"text": kword, "reading": entry["reading"], "dict_id": entry["id"]})
        elif kword in QUESTION_KANJI_READINGS:
            segments.append({"text": kword, "reading": QUESTION_KANJI_READINGS[kword]})
        else:
            segments.append({"text": kword, "reading": None})
        pos = m.end()
    if pos < len(text):
        segments.extend(split_plain_segment(text[pos:], kana_words_sorted, kana_id_map))
    return segments


def main():
    n5_path = PACK_FILES[0]
    n5_data = json.loads(n5_path.read_text(encoding="utf-8"))
    dictionary = n5_data.get("dictionary", [])
    existing_ids = {e["id"] for e in dictionary}
    word_to_entry = {}
    for e in dictionary:
        if e["word"] not in word_to_entry:
            word_to_entry[e["word"]] = e

    # Add Katakana & Hiragana dictionary entries
    kana_id_map = {}
    for word, (trans, pos) in {**KATAKANA_DICT, **HIRAGANA_DICT}.items():
        if word in word_to_entry:
            kana_id_map[word] = word_to_entry[word]["id"]
            continue
        did = make_dict_id("dk", word)
        if did not in existing_ids:
            entry = {
                "id": did,
                "word": word,
                "reading": word,
                "translation_ru": trans,
                "part_of_speech": pos,
                "note": None,
            }
            dictionary.append(entry)
            existing_ids.add(did)
            word_to_entry[word] = entry
        kana_id_map[word] = did

    kana_words_sorted = sorted(kana_id_map.keys(), key=len, reverse=True)

    # Enrich all 3 packs
    for path in PACK_FILES:
        data = json.loads(path.read_text(encoding="utf-8"))
        for mat in data["materials"]:
            for p in mat["paragraphs"]:
                for s in p["sentences"]:
                    new_segs = []
                    for seg in s["segments"]:
                        if seg.get("reading") is None and not seg.get("dict_id"):
                            new_segs.extend(split_plain_segment(seg["text"], kana_words_sorted, kana_id_map))
                        else:
                            new_segs.append(seg)
                    s["segments"] = new_segs

            for q in mat["questions"]:
                q["question_segments"] = annotate_question_text(
                    q["question"], word_to_entry, kana_words_sorted, kana_id_map
                )
                q["option_segments"] = [
                    annotate_question_text(opt, word_to_entry, kana_words_sorted, kana_id_map)
                    for opt in q["options"]
                ]

        data["pack_version"] = 3
        if path.name == "01_n5_pack.json":
            data["dictionary"] = dictionary
        path.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")

    print(f"Enriched all packs to pack_version=3! Total dictionary entries: {len(dictionary)}")


if __name__ == "__main__":
    main()
